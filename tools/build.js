// Generates from tools/domains.txt:
//   rules/ad_domains.json   -> declarativeNetRequest static ruleset
//   content/domains.js      -> domain list for content scripts and background service worker
// Run: node tools/build.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(__dirname, 'domains.txt'), 'utf8');

const lists = { popup: [], display: [] };
let section = null;
for (const raw of src.split(/\r?\n/)) {
  const line = raw.replace(/#.*/, '').trim();
  if (!line) continue;
  const header = line.match(/^\[(\w+)\]$/);
  if (header) {
    section = header[1];
    if (!lists[section]) throw new Error(`Unknown section [${section}]`);
    continue;
  }
  if (!section) throw new Error(`Domain "${line}" is outside a section`);
  const domain = line.toLowerCase();
  if (!/^[a-z0-9.-]+\.[a-z0-9-]+$/.test(domain)) throw new Error(`Invalid domain "${line}"`);
  if (!lists[section].includes(domain)) lists[section].push(domain);
}

const subresourceTypes = [
  'sub_frame', 'script', 'image', 'stylesheet', 'xmlhttprequest',
  'media', 'font', 'ping', 'websocket', 'object', 'other'
];

const rules = [
  {
    id: 1,
    priority: 1,
    action: { type: 'block' },
    condition: { requestDomains: lists.popup, resourceTypes: ['main_frame', ...subresourceTypes] }
  },
  {
    id: 2,
    priority: 1,
    action: { type: 'block' },
    condition: { requestDomains: lists.display, resourceTypes: subresourceTypes }
  }
];

fs.mkdirSync(path.join(root, 'rules'), { recursive: true });
fs.writeFileSync(path.join(root, 'rules', 'ad_domains.json'), JSON.stringify(rules, null, 2) + '\n');

const js = `// AUTO-GENERATED by tools/build.js - Do not edit manually, edit tools/domains.txt instead.
self.__ADDFREE_DOMAINS__ = ${JSON.stringify(lists)};
`;
fs.writeFileSync(path.join(root, 'content', 'domains.js'), js);

console.log(`popup: ${lists.popup.length}, display: ${lists.display.length} domains`);
